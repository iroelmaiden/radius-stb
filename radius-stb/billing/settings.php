function generateClientsConf($conn) {
    $result = $conn->query("SELECT * FROM nas ORDER BY id");
    $clients = $result->fetch_all(MYSQLI_ASSOC);

    $conf = "# Auto-generated by Hotspot Billing - Do not edit manually\n\n";
    $conf .= "client localhost {\n";
    $conf .= "\tipaddr = 127.0.0.1\n";
    $conf .= "\tsecret = testing123\n";
    $conf .= "\tshortname = localhost\n";
    $conf .= "\tnas_type = other\n";
    $conf .= "}\n\n";
    $conf .= "client localhost_ipv6 {\n";
    $conf .= "\tipv6addr = ::1\n";
    $conf .= "\tsecret = testing123\n";
    $conf .= "}\n\n";

    foreach ($clients as $c) {
        $name = preg_replace('/[^a-zA-Z0-9_-]/', '_', $c['shortname'] ?: $c['nasname']);
        $conf .= "client $name {\n";
        $conf .= "\tipaddr = " . $c['nasname'] . "\n";
        $conf .= "\tsecret = \"" . $c['secret'] . "\"\n";
        $conf .= "\tshortname = " . ($c['shortname'] ?: $name) . "\n";
        $conf .= "\tnas_type = " . ($c['type'] ?: 'other') . "\n";
        $conf .= "\trequire_message_authenticator = true\n";
        $conf .= "}\n\n";
    }

    file_put_contents('/etc/freeradius/3.0/clients.conf', $conf);
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $action = $_POST['action'] ?? '';

    if ($action === 'save_whatsapp') {
        $api_url = trim($_POST['api_url'] ?? '');
