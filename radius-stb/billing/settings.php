        $exists = $conn->query("SELECT id FROM whatsapp_settings LIMIT 1");
        if ($exists->num_rows > 0) {
            $conn->query("UPDATE whatsapp_settings SET api_url='$escUrl', api_key='$escKey', sender_phone='$escPhone', provider='$escProv', is_active=$is_active WHERE id=1");
        } else {
