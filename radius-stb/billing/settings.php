        } else {
            setFlash('Test WhatsApp gagal: ' . ($result['msg'] ?? 'Unknown error'), 'danger');
        }
        header('Location: settings.php#whatsapp');
        exit;
    }

    if ($action === 'add') {
        $nasname = trim($_POST['nasname'] ?? '');
        $shortname = trim($_POST['shortname'] ?? '');
        $secret = trim($_POST['secret'] ?? '');
        $type = trim($_POST['type'] ?? 'other');

        if (empty($nasname) || empty($secret)) {
            setFlash('IP/Range dan Secret wajib diisi.', 'danger');
            header('Location: settings.php');
            exit;
        }

        $escNas = $conn->real_escape_string($nasname);
        $escShort = $conn->real_escape_string($shortname);
        $escSecret = $conn->real_escape_string($secret);
        $escType = $conn->real_escape_string($type);

        $conn->query("INSERT INTO nas (nasname, shortname, type, secret) VALUES ('$escNas', '$escShort', '$escType', '$escSecret')");

        generateClientsConf($conn);
        exec('sudo /usr/bin/systemctl restart freeradius 2>&1', $output, $ret);

        setFlash("NAS '$nasname' berhasil ditambahkan." . ($ret === 0 ? '' : ' (restart gagal)'), 'success');
        header('Location: settings.php');
        exit;
    }

    if ($action === 'edit') {
        $id = intval($_POST['id'] ?? 0);
        $nasname = trim($_POST['nasname'] ?? '');
        $shortname = trim($_POST['shortname'] ?? '');
        $secret = trim($_POST['secret'] ?? '');
        $type = trim($_POST['type'] ?? 'other');

        if (empty($nasname) || empty($secret)) {
            setFlash('IP/Range dan Secret wajib diisi.', 'danger');
            header('Location: settings.php');
            exit;
        }

        $escNas = $conn->real_escape_string($nasname);
        $escShort = $conn->real_escape_string($shortname);
        $escSecret = $conn->real_escape_string($secret);
        $escType = $conn->real_escape_string($type);

        $conn->query("UPDATE nas SET nasname='$escNas', shortname='$escShort', secret='$escSecret', type='$escType' WHERE id=$id");

        generateClientsConf($conn);
        exec('sudo /usr/bin/systemctl restart freeradius 2>&1', $output, $ret);

        setFlash("NAS ID $id berhasil diupdate." . ($ret === 0 ? '' : ' (restart gagal)'), 'success');
        header('Location: settings.php');
        exit;
    }

    if ($action === 'delete') {
        $id = intval($_POST['id'] ?? 0);
        $conn->query("DELETE FROM nas WHERE id = $id");

        generateClientsConf($conn);
        exec('sudo /usr/bin/systemctl restart freeradius 2>&1', $output, $ret);

        setFlash("NAS berhasil dihapus." . ($ret === 0 ? '' : ' (restart gagal)'), 'success');
        header('Location: settings.php');
        exit;
    }
}

